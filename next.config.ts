/** Sent on every response. HSTS only in production (it would pin localhost to https). */
const securityHeaders = [
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Content-Security-Policy", value: "frame-ancestors 'none'; base-uri 'self'; object-src 'none'; form-action 'self'" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), payment=(self \"https://js.stripe.com\")" },
  ...(process.env.NODE_ENV === "production" ? [{ key: "Strict-Transport-Security", value: "max-age=31536000; includeSubDomains" }] : []),
];

const nextConfig: NextConfig = {
  // The Laravel app one level up has its own package-lock.json; this is the project root.
  turbopack: { root: path.resolve(/*turbopackIgnore: true*/ ".") },
  poweredByHeader: false,
  async headers() {
    return [
      { source: "/((?!legacy/).*)", headers: securityHeaders },
      // Old uploads: same headers, but a sandboxing CSP so an uploaded SVG can never run script.
      {
        source: "/legacy/:path*",
        headers: securityHeaders.map((h) =>
          h.key === "Content-Security-Policy" ? { ...h, value: "default-src 'none'; img-src 'self' data:; style-src 'unsafe-inline'; font-src 'self'; frame-ancestors 'none'; sandbox" } : h,
        ),
      },
    ];
  },
  async redirects() {
    return legacyAdmin.filter(([a, b]) => a !== b).map(([source, destination]) => ({ source, destination, permanent: false }));
  },
};

export default nextConfig;
