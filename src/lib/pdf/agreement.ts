import "server-only";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { db } from "@/lib/db";
import { PUBLIC_DIR, resolvePublic } from "@/lib/files";
import { pdfDoc } from "./doc";

type U = { id: bigint; fname: string; lname: string; email: string; ip: string | null; api_token: string | null; created_at: Date | null };

const strip = (html: string) => html.replace(/<\/(p|div|li|h\d)>/gi, "\n").replace(/<br\s*\/?>/gi, "\n").replace(/<[^>]+>/g, "").replace(/&nbsp;/g, " ").replace(/&amp;/g, "&").replace(/\n{3,}/g, "\n\n").trim();

/** ssc.mechanic.terms.signable — the mechanic agreement certificate, followed by the mechanic terms. */
async function render(u: U) {
  const pdf = await pdfDoc();
  const at = (u.created_at ?? new Date()).toISOString().replace("T", " ").slice(0, 19);
  pdf.small("Smart Servicing Centre Agreement");
  pdf.title("Smart Servicing Centre (Mechanic Agreement)");
  pdf.row("Issuer", "Smart Servicing Centre");
  pdf.row("Document generated", at);
  pdf.h("Parties involved with this document");
  pdf.row("Document processed", at);
  pdf.row("Party + fingerprint", `${u.fname} ${u.lname} — Signer (${u.api_token ?? ""})`);
  pdf.h("Audit log history");
  pdf.row(at, `The envelope has been signed by all parties. (${u.ip ?? ""})`);
  pdf.row(at, `${u.lname} signed the envelope. (${u.ip ?? ""})`);
  pdf.row(at, `Sent the envelope to ${u.fname} ${u.lname} (${u.email}) for signing.`);
  pdf.row(at, `Document generated with fingerprint (${u.api_token ?? ""})`);
  pdf.row(at, "Envelope generated by Smart Servicing Centre");
  const terms = await db.pages.findFirst({ where: { slug: "mechanic-terms" } });
  if (terms?.description) {
    pdf.rule();
    pdf.h("Mechanic terms & conditions");
    pdf.p(strip(terms.description));
  }
  return Buffer.from(await pdf.save());
}

/** Jobs\SignableJob — store the agreement under public/ssc/signable and record it in `signables`. */
export async function createAgreement(u: U) {
  const name = `ssc/signable/${u.fname}_${u.lname}${Math.floor(Date.now() / 1000)}.pdf`.replace(/[^\w./-]/g, "_");
  const file = path.join(/*turbopackIgnore: true*/ PUBLIC_DIR, name);
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, await render(u));
  const now = new Date();
  await db.signables.create({ data: { user_id: u.id, name, finger_print: u.api_token, created_at: now, updated_at: now } }).catch(() => null);
  return name;
}

/** The mechanic's stored agreement, or a freshly rendered one. */
export async function agreementFor(u: U) {
  const s = await db.signables.findFirst({ where: { user_id: u.id }, orderBy: { id: "desc" } });
  if (s) {
    try {
      return await readFile(resolvePublic(s.name));
    } catch {}
  }
  return render(u);
}
